/**
 * 症例写真（術前術後写真）の掲載要件。
 *
 * 医療広告ガイドラインでは、術前術後写真は原則として広告できない。
 * 「限定解除」の要件を満たしたウェブサイト等でのみ、詳細な説明を併記して掲載できる。
 *
 * **写真そのものを生成して代用することはできない。** 実在しない治療結果を
 * 掲載すれば医療法第6条の5の虚偽広告になる。ここで用意するのは、
 * 院が自院の実症例を差し込むための「枠」と、併記が必要な項目の定義。
 *
 * 出典: 医療広告ガイドライン／医療広告規制におけるウェブサイト等の事例解説書
 * https://www.mhlw.go.jp/content/001439423.pdf
 */

export type CaseField = {
  key: string;
  label: string;
  /** 何を書くのか。空欄のまま出させないための説明 */
  hint: string;
};

/** 限定解除の4要件。これを満たさない媒体には症例写真を出せない */
export const LIMITED_RELEASE = [
  "患者等が自ら求めて入手する情報であること（ウェブサイト・メールマガジン・院内パンフレット等）。新聞広告・雑誌・チラシ・テレビCM・看板には掲載できない",
  "表示内容について患者等が容易に照会できるよう、問い合わせ先（電話番号・メールアドレス等）を明記していること",
  "自由診療について、通常必要とされる治療等の内容・費用等に関する事項を情報提供していること",
  "自由診療について、治療等に係る主なリスク・副作用等に関する事項を情報提供していること",
];

/** 写真に直接併記する項目。別ページに書くのは不可 */
export const CASE_FIELDS: CaseField[] = [
  { key: "treatment", label: "治療内容", hint: "術式名だけでなく、方法・手順まで書く（例：セラミックラミネートベニア。歯面を最小限整形し、専用接着材で薄いセラミックを接着）" },
  { key: "price", label: "標準的な費用", hint: "税込の総額。本数・範囲など内訳も書く（例：1歯 88,000円（税込）／上顎前歯6歯 528,000円）" },
  { key: "period", label: "治療期間・回数", hint: "曖昧にしない（例：約3週間・通院3回）" },
  { key: "risk", label: "主なリスク・副作用", hint: "起こり得るものを列挙する。「ほぼない」等の断定はしない（例：知覚過敏、色調の不一致、破折・脱離、再製作が必要になる場合がある）" },
  { key: "note", label: "個人差の注記", hint: "「効果や結果には個人差があります」を必ず入れる" },
];

/** 撮影・掲載時の遵守事項 */
export const CASE_RULES = [
  "加工・修正をしない（明るさ・色調の補正を含め、結果が変わって見える処理はしない）",
  "術前と術後で撮影場所・角度・照明・メイク・髪型をそろえる",
  "18歳未満の術前術後写真は掲載しない",
  "複数の治療を並べる場合は、写真ごとに情報を1セットずつ付ける",
  "併記する情報は写真に直接付記する。別ページへのリンクで代替しない",
];

/** その施策が症例写真に関わるか。関わるなら要件を持ち回る必要がある */
export function isCasePhoto(text: string) {
  return /症例写真|ビフォーアフター|before\s*[&/-]?\s*after|術前術後|施術前後/i.test(text);
}

/** 生成プロンプトに埋め込む要件テキスト */
export function casePhotoRules() {
  return `【症例写真（術前術後写真）の掲載要件・医療広告ガイドライン】
※ 写真そのものを生成してはならない。実在しない治療結果の掲載は医療法第6条の5の虚偽広告にあたる。
　 成果物は「院が自院の実症例を差し込むための枠」と、併記文の下書きに限る。

限定解除の要件（すべて満たす媒体にのみ掲載可）:
${LIMITED_RELEASE.map((x, i) => `${i + 1}. ${x}`).join("\n")}

写真に直接併記する項目（別ページ不可）:
${CASE_FIELDS.map((f) => `- ${f.label}：${f.hint}`).join("\n")}

撮影・掲載の遵守事項:
${CASE_RULES.map((x) => `- ${x}`).join("\n")}`;
}
